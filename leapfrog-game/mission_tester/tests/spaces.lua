-- Which space a mission flies to, the corners of a space, launching in free
-- play, and starting one mission from another

test("spaces: only the lower right corner of the big space leads anywhere", function(t)
   t:newGame()
   t:menuTestStart(2)
   t:expectScene("deep_space_scene.xml")
   t:expectCorner(1, false)
   t:expectCorner(2, false)
   t:expectCorner(3, true)
   t:expectCorner(4, false)
end)

test("spaces: flying into a shut corner leaves the Leapfrog in the scene", function(t)
   t:newGame()
   t:menuTestStart(2)
   for _, corner in ipairs({ 1, 2, 4 }) do
      t:flyToCorner(corner)
      t:expectScene("deep_space_scene.xml")
   end
   t:expect(t.engine:getObject("leapfrog1") ~= nil, "the Leapfrog is still there")
   t:flyToCorner(3)
   t:expectScene("orbit_scene.xml")
end)

test("spaces: without a space of its own, a mission flies to the big space", function(t)
   t:newGame()
   t:menuTestStart(2)
   t:expectEqual(t.engine:callLuaResults("lua_missionSpace")[1], "deep_space_scene.xml", "space")
end)

test("spaces: the Debris Belt's rocks can be watched, the big space has no watch", function(t)
   t:newGame()
   t:menuTestStart(2)
   t:expect(next(t.engine.scene.watches) == nil, "no watch in the big space")
   t:expect(t.engine.scene.factories["asteroidField"], "the big space has a field too")
end)

test("spaces: a rock's speed comes from the scene", function(t)
   local xml = require("testbench.xml")
   local root = xml.readFile(require("testbench.harness").dataDir .. "/debris_belt_scene.xml")
   t:expect(root ~= nil, "debris_belt_scene.xml can't be read")
   local behaviour = xml.child(root, "behaviour")
   local props = xml.child(behaviour, "sceneProperties")
   t:expect(tonumber(props.attr.rockSpeedMin) > 8, "faster than the old nudge")
   t:expect(tonumber(props.attr.rockSpeedMax) >= tonumber(props.attr.rockSpeedMin), "max is at least min")
end)

test("launching: the launch site works in free play", function(t)
   t:newGame()
   t.engine:callLua("lua_startMission", 0)
   t:launch("launchSite1")
   t:expectScene("deep_space_scene.xml")
end)

test("launching: free play saves and continues", function(t)
   t:newGame()
   t.engine:callLua("lua_startMission", 0)
   t:launch("launchSite1")
   t:expectSaved("mission", 0)
   t:restartGame()
   t:expectScene("deep_space_scene.xml")
   t:expect(t.engine:getObject("leapfrog1") ~= nil, "the Leapfrog is there")
end)

test("missions: lua_startMission outside an event starts at once", function(t)
   t:newGame()
   t.engine:callLua("lua_startMission", 2)
   t:expectMission(2)
   t:expectState(t:mission(2).firstState)
end)

test("missions: a new mission takes back the old mission's questions only", function(t)
   t:newGame()
   t:expectQuestionQueued(t:mission(1).Question.takeJob)
   t:askQuestion(100, "Repair?", "Silo")
   t.engine:callLua("lua_startMission", 2)
   t:expectQuestionQueued(100)
   t:expectQuestionQueued(t:mission(2).Question.acceptJob)
   t:land("siloLandingPad")
   t:expectQuestion(100)
end)

test("missions: the next mission is saved at the next scene exit", function(t)
   t:newGame()
   t.engine:callLua("lua_startMission", 2)
   t:land("siloLandingPad")
   t:answer(t:mission(2).Question.acceptJob, false)
   t:takeOff()
   t:launch("launchSite1")
   t:expectSaved("mission", 2)
end)
