-- Key items (data/key_items.xml; GameStatus keeps their states, saved with
-- the game): c_hasItem, c_itemState, c_itemInfo, c_giveItem, c_revokeItem,
-- c_forgetItem, c_itemsHeld

-- Mission 1 at home with the job accepted, on the Orb's pad, ready to launch
local function atOrb(t)
   t:newGame()
   local m = t:mission(1)
   t:land("siloLandingPad")
   t:answer(m.Question.acceptJob, true)
   t:land("oreLanding")
   t:takeOff()
end

local function call(t, fn, ...)
   return t.engine.env[fn](...)
end

test("key items: the initial ones are held in a new game, the others unknown", function(t)
   t:declareKeyItem({ id = "testPass", kind = "pass", name = "Test pass" })
   t:newGame()
   t:expectItem("goldMineSolution", "held")
   t:expectItem("alphaCitySolution", "held")
   t:expectItem("testPass", "unknown")
   t:expectEqual(call(t, "c_hasItem", "testPass"), false, "c_hasItem")
   t:expectEqual(call(t, "c_itemState", "goldMineSolution"), "held", "c_itemState")
end)

test("key items: given, held; saved at the next scene exit; kept on continuing", function(t)
   t:declareKeyItem({ id = "testPass", kind = "pass", name = "Test pass" })
   atOrb(t)
   t:giveItem("testPass")
   t:expectItem("testPass", "held")
   t:expectHud("Pass received: Test pass")
   t:expectSavedItem("testPass", "unknown")
   t:launch("launchSite1")
   t:expectSavedItem("testPass", "held")
   t:restartGame()
   t:expectItem("testPass", "held")
end)

test("key items: one given since the last save is gone after loading it", function(t)
   t:declareKeyItem({ id = "testPass", kind = "pass", name = "Test pass" })
   atOrb(t)
   t:launch("launchSite1")
   t:giveItem("testPass")
   t:restartGame()
   t:expectItem("testPass", "unknown")
end)

test("key items: revoked, then given back", function(t)
   t:declareKeyItem({ id = "testPass", kind = "pass", name = "Test pass" })
   atOrb(t)
   t:giveItem("testPass")
   t:revokeItem("testPass")
   t:expectItem("testPass", "revoked")
   t:expectHud("Pass revoked: Test pass")
   t:expectEqual(call(t, "c_hasItem", "testPass"), false, "c_hasItem")
   t:giveItem("testPass")
   t:expectItem("testPass", "held")
end)

test("key items: an initial one revoked stays revoked after saving and continuing", function(t)
   atOrb(t)
   t:revokeItem("alphaCitySolution")
   t:expectHud("Landing solution revoked: Village solution")
   t:launch("launchSite1")
   t:expectSavedItem("alphaCitySolution", "revoked")
   t:restartGame()
   t:expectItem("alphaCitySolution", "revoked")
end)

test("key items: forgotten knowledge is unknown again", function(t)
   atOrb(t)
   t:forgetItem("goldMineSolution")
   t:expectItem("goldMineSolution", "unknown")
   t:expectHud("Landing solution lost: Claude Mine solution")
end)

test("key items: quiet changes leave no HUD line; no line when nothing changes", function(t)
   t:declareKeyItem({ id = "testPass", kind = "pass", name = "Test pass" })
   atOrb(t)
   local before = #t.engine.hud
   t:giveItem("testPass", true)
   t:giveItem("goldMineSolution")          -- already held
   t:revokeItem("testPass", true)
   t:expectEqual(#t.engine.hud, before, "HUD lines")
   t:expectItem("testPass", "revoked")
end)

test("key items: c_itemsHeld lists the held ones, by kind", function(t)
   t:declareKeyItem({ id = "testPass", kind = "pass", name = "Test pass" })
   t:declareKeyItem({ id = "testRoute", kind = "route", name = "Test route" })
   atOrb(t)
   t:giveItem("testRoute")
   local all = call(t, "c_itemsHeld")
   local routes = call(t, "c_itemsHeld", "route")
   local passes = call(t, "c_itemsHeld", "pass")
   t:expectEqual(#all, 3, "held items")
   t:expectEqual(routes[1], "testRoute", "held route")
   t:expectEqual(#passes, 0, "held passes")
end)

test("key items: c_itemInfo", function(t)
   t:declareKeyItem({ id = "testPass", kind = "pass", name = "Test pass", issuer = "miners", tier = 2 })
   atOrb(t)
   local info = call(t, "c_itemInfo", "testPass")
   t:expectEqual(info.name, "Test pass", "name")
   t:expectEqual(info.kind, "pass", "kind")
   t:expectEqual(info.issuer, "miners", "issuer")
   t:expectEqual(info.tier, 2, "tier")
   t:expectEqual(info.state, "unknown", "state")
end)

test("key items: a new game starts over", function(t)
   t:declareKeyItem({ id = "testPass", kind = "pass", name = "Test pass" })
   atOrb(t)
   t:giveItem("testPass")
   t:revokeItem("alphaCitySolution")
   t:launch("launchSite1")
   t:menuNewGame()
   t:expectItem("testPass", "unknown")
   t:expectItem("alphaCitySolution", "held")
end)

test("key items: an undeclared id is a problem", function(t)
   atOrb(t)
   t:allowProblem("no key item noSuchItem in key_items.xml")
   t:giveItem("noSuchItem")
   t:expectEqual(call(t, "c_hasItem", "noSuchItem"), false, "c_hasItem")
end)
