   t:expectProperty("landingPad2", 3, t:module("mining").beaconFuel)
end)

test("mission 1: the offer asked in flight opens on the first pad, even the Ore's", function(t)
   t:newGame()
   local m = t:mission(1)
   t:clearDialog()
   t:setProperty("leapfrog1", 7, 1)
